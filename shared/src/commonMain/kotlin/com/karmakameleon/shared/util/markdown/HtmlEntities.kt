package com.karmakameleon.shared.util.markdown

// Matches a character reference: &name;, &#123; or &#x1F600;.
private val entityPattern = Regex("""&(?:#[xX]([0-9a-fA-F]{1,6})|#([0-9]{1,7})|([A-Za-z][A-Za-z0-9]{1,31}));""")

private const val REPLACEMENT_CHARACTER = 0xFFFD
private const val MAX_CODE_POINT = 0x10FFFF
private const val MIN_SUPPLEMENTARY_CODE_POINT = 0x10000
private const val SURROGATES_START = 0xD800
private const val SURROGATES_END = 0xDFFF
private const val LOW_SURROGATE_START = 0xDC00
private const val SURROGATE_BITS = 10
private const val LOW_SURROGATE_MASK = 0x3FF

// The character reference that starts at index in text, as the text it stands for and the index just after it, or
// null when there's none, or it names an entity that doesn't exist. As in CommonMark, a number that isn't a
// character, like &#0;, stands for U+FFFD.
internal fun htmlEntityAt(
    text: String,
    index: Int,
): Pair<String, Int>? {
    val match = entityPattern.matchAt(text, index) ?: return null
    val (hex, decimal, name) = match.destructured
    val codePoint =
        when {
            hex.isNotEmpty() -> hex.toInt(radix = 16)
            decimal.isNotEmpty() -> decimal.toInt()
            else -> namedEntities[name] ?: return null
        }
    return codePointToString(codePoint) to match.range.last + 1
}

private fun codePointToString(codePoint: Int): String {
    val valid = codePoint in 1..MAX_CODE_POINT && codePoint !in SURROGATES_START..SURROGATES_END
    val cp = if (valid) codePoint else REPLACEMENT_CHARACTER
    if (cp < MIN_SUPPLEMENTARY_CODE_POINT) return Char(cp).toString()
    val offset = cp - MIN_SUPPLEMENTARY_CODE_POINT
    return charArrayOf(
        Char(SURROGATES_START + (offset shr SURROGATE_BITS)),
        Char(LOW_SURROGATE_START + (offset and LOW_SURROGATE_MASK)),
    ).concatToString()
}

